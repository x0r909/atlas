"""0001 core: operator, rollout state, risk config, venues, equity baseline.

Hand-written SQL on purpose (see infra/db/env.py): these columns are the money and
authority surface, so each one is reviewed rather than autogenerated. Downgrade drops the
objects it created and nothing else.
"""

from __future__ import annotations

from alembic import op

from atlas_common.sqlsplit import apply_statements

revision = "0001_core"
down_revision = None
branch_labels = None
depends_on = None


UPGRADE = """
CREATE TYPE mode_stage AS ENUM ('BACKTEST', 'PAPER', 'CO_PILOT', 'AUTONOMOUS', 'HALTED');
CREATE TYPE mode_reason_code AS ENUM (
    'OPERATOR_PROMOTION', 'OPERATOR_DEMOTION', 'AUTO_DEMOTE', 'STARTUP_DEFAULT',
    'KILL_SWITCH', 'RECOVERY'
);
CREATE TYPE mode_actor AS ENUM ('OPERATOR', 'SYSTEM');
CREATE TYPE venue_regulator AS ENUM ('OJK', 'BAPPEBTI_LEGACY', 'NONE');
CREATE TYPE venue_status AS ENUM ('ACTIVE', 'DEGRADED', 'DISABLED');
CREATE TYPE tax_applies_to AS ENUM ('SELL_ONLY', 'BOTH_SIDES');
CREATE TYPE live_stage AS ENUM ('CO_PILOT', 'AUTONOMOUS');

CREATE TABLE operator (
    id                    uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    username              text NOT NULL UNIQUE,
    totp_secret_enc       bytea,
    passkey_credentials   jsonb NOT NULL DEFAULT '[]'::jsonb,
    telegram_user_id      bigint UNIQUE,
    created_at            timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT operator_username_not_blank CHECK (btrim(username) <> ''),
    CONSTRAINT operator_passkeys_is_array CHECK (jsonb_typeof(passkey_credentials) = 'array')
);

CREATE TABLE mode_state (
    id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    -- Monotonic, and the only ordering the rollout guard trusts: created_at is
    -- transaction-constant and id is random, so neither can say which row is current.
    seq              bigint GENERATED ALWAYS AS IDENTITY UNIQUE,
    mode             mode_stage NOT NULL,
    previous_mode    mode_stage,
    reason_code      mode_reason_code NOT NULL,
    capital_cap_idr  numeric(28,10),
    actor            mode_actor NOT NULL,
    -- Who acted, when the actor is a person: the enum says OPERATOR, this says which one.
    actor_ref        text,
    evidence_ref     uuid,
    created_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT mode_state_cap_positive CHECK (capital_cap_idr IS NULL OR capital_cap_idr > 0),
    CONSTRAINT mode_state_promotion_has_evidence CHECK (
        reason_code <> 'OPERATOR_PROMOTION' OR evidence_ref IS NOT NULL
    ),
    CONSTRAINT mode_state_system_actor_is_automatic CHECK (
        actor <> 'SYSTEM' OR reason_code IN ('AUTO_DEMOTE', 'STARTUP_DEFAULT', 'RECOVERY')
    ),
    CONSTRAINT mode_state_operator_actor CHECK (
        actor <> 'OPERATOR' OR reason_code IN (
            'OPERATOR_PROMOTION', 'OPERATOR_DEMOTION', 'KILL_SWITCH', 'RECOVERY'
        )
    )
);
CREATE INDEX mode_state_latest_idx ON mode_state (seq DESC);

CREATE TABLE risk_config (
    version                      int PRIMARY KEY,
    risk_per_trade_pct           numeric(6,3) NOT NULL DEFAULT 0.500,
    max_position_pct             numeric(6,3) NOT NULL DEFAULT 25.000,
    max_asset_exposure_pct       numeric(6,3) NOT NULL DEFAULT 50.000,
    max_total_exposure_pct       numeric(6,3) NOT NULL DEFAULT 100.000,
    max_daily_loss_pct           numeric(6,3) NOT NULL DEFAULT 2.000,
    max_drawdown_pct             numeric(6,3) NOT NULL DEFAULT 10.000,
    min_rr_net                   numeric(6,3) NOT NULL DEFAULT 1.500,
    max_slippage_pct             numeric(6,3) NOT NULL DEFAULT 0.300,
    max_spread_multiple          numeric(6,2) NOT NULL DEFAULT 3.00,
    volatility_breaker_sigma     numeric(6,2) NOT NULL DEFAULT 5.00,
    stale_price_seconds          int NOT NULL DEFAULT 10,
    cooldown_after_losses        int NOT NULL DEFAULT 3,
    cooldown_hours               int NOT NULL DEFAULT 4,
    time_stop_hours              int NOT NULL DEFAULT 120,
    max_open_positions           int NOT NULL DEFAULT 5,
    max_orders_per_hour          int NOT NULL DEFAULT 6,
    llm_daily_cap_idr            int NOT NULL DEFAULT 5000,
    llm_monthly_cap_idr          int NOT NULL DEFAULT 250000,
    effective_from               timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT risk_config_version_positive CHECK (version > 0),
    CONSTRAINT risk_config_pct_positive CHECK (
        risk_per_trade_pct > 0 AND max_position_pct > 0 AND max_asset_exposure_pct > 0
        AND max_total_exposure_pct > 0 AND max_daily_loss_pct > 0 AND max_drawdown_pct > 0
        AND min_rr_net > 0 AND max_slippage_pct >= 0 AND max_spread_multiple > 0
        AND volatility_breaker_sigma > 0
    ),
    -- Upper bounds, not only lower: a percentage of 900 defeats the breaker it configures.
    CONSTRAINT risk_config_pct_upper_bounds CHECK (
        risk_per_trade_pct <= 10 AND max_position_pct <= 100
        AND max_asset_exposure_pct <= 100 AND max_total_exposure_pct <= 100
        AND max_daily_loss_pct <= 100 AND max_drawdown_pct <= 100
        AND max_slippage_pct <= 100 AND max_spread_multiple <= 100
    ),
    CONSTRAINT risk_config_pct_ordering CHECK (
        risk_per_trade_pct <= max_position_pct
        AND max_position_pct <= max_asset_exposure_pct
        AND max_asset_exposure_pct <= max_total_exposure_pct
        AND max_daily_loss_pct <= max_drawdown_pct
    ),
    CONSTRAINT risk_config_counts_positive CHECK (
        stale_price_seconds > 0 AND cooldown_after_losses >= 0 AND cooldown_hours >= 0
        AND time_stop_hours BETWEEN 4 AND 120 AND max_open_positions > 0
        AND max_orders_per_hour > 0 AND llm_daily_cap_idr >= 0 AND llm_monthly_cap_idr >= 0
    )
);

CREATE TABLE venue (
    id                 text PRIMARY KEY,
    display_name       text NOT NULL,
    regulator          venue_regulator NOT NULL,
    enabled_for_live   boolean NOT NULL DEFAULT false,
    quote_currencies   text[] NOT NULL DEFAULT ARRAY['IDR'],
    api_base           text NOT NULL,
    ws_url             text,
    status             venue_status NOT NULL DEFAULT 'ACTIVE',
    CONSTRAINT venue_live_requires_ojk CHECK (NOT enabled_for_live OR regulator = 'OJK')
);

CREATE TABLE venue_profile (
    id                     bigserial PRIMARY KEY,
    venue_id               text NOT NULL REFERENCES venue (id),
    version                int NOT NULL,
    fee_maker_pct          numeric(7,5) NOT NULL,
    fee_taker_pct          numeric(7,5) NOT NULL,
    cfx_fee_pct            numeric(7,5),
    cfx_fee_pct_assumed    numeric(7,5) NOT NULL,
    tax_buy_pct_assumed    numeric(7,5) NOT NULL DEFAULT 0.21000,
    tax_pph_pct            numeric(7,5) NOT NULL,
    tax_ppn_pct            numeric(7,5) NOT NULL,
    tax_applies_to         tax_applies_to NOT NULL,
    min_notional_idr       numeric(18,2) NOT NULL,
    min_order_step         jsonb NOT NULL,
    tick_size              jsonb NOT NULL,
    rate_limit             jsonb NOT NULL,
    max_leverage           int NOT NULL DEFAULT 1,
    native_stop_orders     boolean NOT NULL,
    supports_order_modify  boolean NOT NULL DEFAULT false,
    cost_model_version     text NOT NULL,
    verified_at            timestamptz NOT NULL,
    created_at             timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT venue_profile_version_unique UNIQUE (venue_id, version),
    CONSTRAINT venue_profile_version_positive CHECK (version > 0),
    CONSTRAINT venue_profile_spot_only CHECK (max_leverage = 1),
    CONSTRAINT venue_profile_fees_non_negative CHECK (
        fee_maker_pct >= 0 AND fee_taker_pct >= 0 AND tax_pph_pct >= 0 AND tax_ppn_pct >= 0
        AND cfx_fee_pct_assumed >= 0 AND tax_buy_pct_assumed >= 0
        AND (cfx_fee_pct IS NULL OR cfx_fee_pct >= 0)
    ),
    -- An assumed cost must be a real assumption: 0 would make the cost model look
    -- verified (and profitable) exactly where the truth is unknown.
    CONSTRAINT venue_profile_assumed_cfx_is_positive CHECK (cfx_fee_pct_assumed > 0),
    CONSTRAINT venue_profile_assumed_cfx_is_pessimistic CHECK (
        cfx_fee_pct IS NULL OR cfx_fee_pct_assumed >= cfx_fee_pct
    ),
    CONSTRAINT venue_profile_assumed_cfx_is_floor CHECK (
        cfx_fee_pct IS NOT NULL OR cfx_fee_pct_assumed >= 0.10000
    ),
    CONSTRAINT venue_profile_order_rules_present CHECK (
        jsonb_typeof(tick_size) = 'object' AND tick_size <> '{}'::jsonb
        AND jsonb_typeof(min_order_step) = 'object' AND min_order_step <> '{}'::jsonb
    ),
    CONSTRAINT venue_profile_min_notional_positive CHECK (min_notional_idr > 0)
);

CREATE TABLE equity_baseline (
    id                     uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    mode_stage             live_stage NOT NULL,
    day_start_equity_idr   numeric(28,10) NOT NULL,
    day_started_on         date NOT NULL,
    peak_equity_idr        numeric(28,10) NOT NULL,
    stage_started_at       timestamptz NOT NULL,
    created_at             timestamptz NOT NULL DEFAULT now(),
    closed_at              timestamptz,
    CONSTRAINT equity_baseline_positive CHECK (
        day_start_equity_idr > 0 AND peak_equity_idr > 0
    ),
    CONSTRAINT equity_baseline_peak_covers_day_start CHECK (
        peak_equity_idr >= day_start_equity_idr
    ),
    CONSTRAINT equity_baseline_closed_after_created CHECK (
        closed_at IS NULL OR closed_at >= created_at
    )
);
CREATE UNIQUE INDEX equity_baseline_one_open_per_stage
    ON equity_baseline (mode_stage) WHERE closed_at IS NULL;

INSERT INTO venue (id, display_name, regulator, enabled_for_live, api_base, ws_url)
VALUES ('indodax', 'Indodax', 'BAPPEBTI_LEGACY', false,
        'https://indodax.com', 'wss://ws3.indodax.com/ws/')
ON CONFLICT (id) DO NOTHING;
"""

DOWNGRADE = """
DROP TABLE IF EXISTS equity_baseline;
DROP TABLE IF EXISTS venue_profile;
DROP TABLE IF EXISTS venue;
DROP TABLE IF EXISTS risk_config;
DROP TABLE IF EXISTS mode_state;
DROP TABLE IF EXISTS operator;
DROP TYPE IF EXISTS live_stage;
DROP TYPE IF EXISTS tax_applies_to;
DROP TYPE IF EXISTS venue_status;
DROP TYPE IF EXISTS venue_regulator;
DROP TYPE IF EXISTS mode_actor;
DROP TYPE IF EXISTS mode_reason_code;
DROP TYPE IF EXISTS mode_stage;
"""


def upgrade() -> None:
    apply_statements(op.get_bind(), UPGRADE)


def downgrade() -> None:
    apply_statements(op.get_bind(), DOWNGRADE)
